def env(nombre, defecto=None):
    """Lee una variable de entorno; si no existe y no hay valor por defecto, avisa."""
    valor = os.environ.get(nombre, defecto)
    if valor is None:
        raise RuntimeError(
            f"Falta la variable de entorno {nombre}. "
            "Copia .env.example a .env y revisa sus valores."
        )
    return valor

